const Context = createContext<{ locale: Locale; t: (text: string) => string }>({
  locale: 'en',
  t: (v) => v,
});
export function LocaleProvider({
  locale,
  children,
}: {
  locale: Locale;
  children: React.ReactNode;
}) {
  return (
    <Context.Provider
      value={{ locale, t: (text) => (locale === 'ar' ? arabic[text] || text : text) }}
    >
      {children}
    </Context.Provider>
  );
}
export const useLocale = () => useContext(Context);
