    public static string T(string text) => Arabic && Labels.TryGetValue(text, out var value) ? value : text;
    public static void Apply(Microsoft.UI.Xaml.DependencyObject element)
    {
        if (element is Microsoft.UI.Xaml.Controls.TextBlock text) text.Text = T(text.Text);
        if (element is Microsoft.UI.Xaml.Controls.ContentControl control && control.Content is string content) control.Content = T(content);
        if (element is Microsoft.UI.Xaml.Controls.ComboBox combo && combo.Header is string comboHeader) combo.Header = T(comboHeader);
        if (element is Microsoft.UI.Xaml.Controls.TextBox input && input.Header is string header) input.Header = T(header);
        if (element is Microsoft.UI.Xaml.Controls.ToggleSwitch toggle) { if (toggle.Header is string toggleHeader) toggle.Header = T(toggleHeader); toggle.OnContent = toggle.OnContent is string on && on != "开" ? T(on) : T("On"); toggle.OffContent = toggle.OffContent is string off && off != "关" ? T(off) : T("Off"); }
        if (element is Microsoft.UI.Xaml.Controls.AutoSuggestBox suggest) suggest.PlaceholderText = T(suggest.PlaceholderText);
        if (element is Microsoft.UI.Xaml.Controls.ContentDialog dialog) { if (dialog.Title is string title) dialog.Title = T(title); dialog.PrimaryButtonText = T(dialog.PrimaryButtonText); dialog.SecondaryButtonText = T(dialog.SecondaryButtonText); dialog.CloseButtonText = T(dialog.CloseButtonText); }
        for (var i = 0; i < Microsoft.UI.Xaml.Media.VisualTreeHelper.GetChildrenCount(element); i++) Apply(Microsoft.UI.Xaml.Media.VisualTreeHelper.GetChild(element, i));
    }
